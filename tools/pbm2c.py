#!/usr/bin/env python3
"""Turns plain PBM files (P1) into the C table of src/ui/icon.h.

    pbm2c.py OUT.c IN.pbm...

Each icon is named after its file, without the extension. The table is
in name order. Rows are packed most significant bit first, as
blit_1bpp reads them. A 1 in the PBM is a set pixel.
"""

import os
import re
import sys

NAME = re.compile(r"^[a-z][a-z0-9_]*$")


class PbmError(Exception):
    pass


def parse(text):
    """Returns (width, height, rows of 0/1 ints) from plain PBM text."""
    tokens = []
    for line in text.splitlines():
        line = line.split("#", 1)[0]
        tokens.extend(line.split())
    if not tokens or tokens[0] != "P1":
        raise PbmError("not a plain PBM: the magic is not P1")
    if len(tokens) < 3:
        raise PbmError("no size")
    try:
        w, h = int(tokens[1]), int(tokens[2])
    except ValueError:
        raise PbmError("the size is not two numbers") from None
    if not (1 <= w <= 320 and 1 <= h <= 240):
        raise PbmError(f"size {w}x{h} is outside 1x1 to 320x240")
    # Plain PBM pixels may run together: "0110" is four pixels.
    bits = "".join(tokens[3:])
    if set(bits) - {"0", "1"}:
        raise PbmError("a pixel is not 0 or 1")
    if len(bits) != w * h:
        raise PbmError(f"{len(bits)} pixels for {w}x{h}")
    return w, h, [[int(b) for b in bits[r * w:(r + 1) * w]] for r in range(h)]


def pack(w, rows):
    """Rows of bits to bytes, most significant bit first."""
    stride = (w + 7) // 8
    out = []
    for row in rows:
        for i in range(stride):
            byte = 0
            for b in range(8):
                x = i * 8 + b
                if x < w and row[x]:
                    byte |= 0x80 >> b
            out.append(byte)
    return stride, out


def generate(icons):
    """icons: list of (name, w, h, rows). Returns the C source."""
    lines = ["/* Generated by tools/pbm2c.py from assets/. Do not edit. */",
             '#include "ui/icon.h"', ""]
    table = []
    for name, w, h, rows in sorted(icons):
        stride, data = pack(w, rows)
        lines.append(f"static const uint8_t {name}_bits[{len(data)}] = {{")
        for r in range(h):
            row = data[r * stride:(r + 1) * stride]
            lines.append("    " + ", ".join(f"0x{b:02x}" for b in row) + ",")
        lines.append("};")
        lines.append("")
        table.append(f'    {{ "{name}", {w}, {h}, {stride}, {name}_bits }},')
    lines.append(f"const dx_icon_t dx_icons[{max(len(table), 1)}] = {{")
    lines.extend(table if table else ["    { \"\", 0, 0, 0, 0 },"])
    lines.append("};")
    lines.append("")
    lines.append(f"const int dx_icon_count = {len(table)};")
    return "\n".join(lines) + "\n"


def main(argv):
    if len(argv) < 2:
        print("usage: pbm2c.py OUT.c IN.pbm...", file=sys.stderr)
        return 2
    out, inputs = argv[0], argv[1:]
    icons = []
    for path in inputs:
        name = os.path.splitext(os.path.basename(path))[0]
        if not NAME.match(name):
            print(f"{path}: the name must be lowercase letters, digits and _", file=sys.stderr)
            return 1
        try:
            with open(path, encoding="ascii") as f:
                w, h, rows = parse(f.read())
        except (PbmError, UnicodeDecodeError) as e:
            print(f"{path}: {e}", file=sys.stderr)
            return 1
        icons.append((name, w, h, rows))
    text = generate(icons)
    os.makedirs(os.path.dirname(out) or ".", exist_ok=True)
    with open(out + ".tmp", "w", encoding="ascii") as f:
        f.write(text)
    os.replace(out + ".tmp", out)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
